            <section class="privacy-section">
                <h3 class="section-title">1. Reglement</h3>
                <p class="section-text">
                    Bienvenue sur <strong>le reglement de Lyon Palme</strong>.Merci de respecter les règles suivantes.<br>
                    Règlement Intérieur du club LYON PALME<br><br>

I. Objet
Conformément aux statuts, le règlement intérieur précise les modalités de fonctionnement de la
pratique des sports subaquatiques au club LYON PALME.
Chaque membre du club s'engage à accepter et respecter les statuts et le présent règlement
intérieur du club, ainsi que le règlement intérieur du Centre Nautique Intercommunal de Vénissieux,
lieu des activités en piscine du club LYON PALME .
Le non-respect des statuts ou des règlements susnommés, fera l'objet d'un avertissement qui en cas
de récidive peut aller jusqu'à l'exclusion du club.<br><br>

II. Les grands principes
Le club LYON PALME est une association loi 1901, dont tous les membres sont des bénévoles. En
devenant membre du club, on doit garder à l’esprit que le fait de payer une cotisation ne donne
pas droit à une prestation de service, mais donne droit et devoir à participer à la vie du club.
Le club LYON PALME a pour principales activités la pratique de la nage avec palme(s) en piscine et
en milieu naturel, et est rattaché à la Fédération Française d’Etudes et de Sports Sous-Marins
(FFESSM).<br>
Le club LYON PALME et ses membres s'engagent à contribuer aux respects des lois et règlements
ayant pour objet la conservation de la faune, de la flore et des richesses sous-marines.
De même, le club LYON PALME et ses membres s’engagent à :<br><br>

● Assurer la liberté d’opinion<br>
● Interdire toute discrimination<br>
● Veiller aux principes fondamentaux du respect et de la politesse
● Veiller aux respects des règles déontologiques du sport définies par le comité olympique et sportif français<br>
● Respecter les règles d’encadrement, d’hygiène et de sécurité applicables en tout
lieu, aux disciplines sportives pratiquées par ses adhérents.<br><br>

III. Fonctionnement de l’association<br>
Le Club est administré par un bureau directeur (défini par les statuts) élu sur un mandat de 1 an, par
vote à main levé, lors d’une Assemblée Générale. Tout adhérent à jour de ses cotisations peut se
porter candidat à ce bureau.<br>
1. Adhésion annuelle<br>
La saison sportive, conformément aux statuts de la FFESSM, débute en septembre de l’année en
cours pour se terminer en août de l’année suivante.
L’adhésion annuelle au club LYON PALME se fera donc pour l’ensemble de la saison sportive en
cours.<br>
Toutefois, la pratique des activités du club LYON PALME au centre nautique de Vénissieux s’arrête
en début du mois de juin. De ce fait le club LYON PALME de juin à août continue ses activités
uniquement en milieu naturel.<br><br>

Les personnes désirant adhérer doivent au moment de leur adhésion :<br><br>

● Remplir un dossier d’inscription<br>  
● Payer la cotisation demandée<br>
● Fournir un certificat médical de non-contre-indication à la pratique de la nage avec
palme(s) et/ou de l’apnée.<br><br>

Pour les compétiteurs, le certificat médical doit préciser en toutes lettres que la ou les disciplines
pratiquées peuvent l’être dans le cadre de compétitions et contenir toutes les autres mentions
éventuellement imposées par la FFESSM.<br>
Pour les mineurs de moins de 16 ans, ces formalités sont à réaliser par un représentant légal.
L’accès aux entraînements en piscine ou en milieu naturel sera refusé en cas de non-remise du
certificat lors de l’inscription (une tolérance sera accordée pendant les premières semaines
d'entraînement mais pas plus tard que fin septembre), et tant qu’il ne sera pas remis. Dans ce cas
de figure, les adhérents mineurs n’auront pas accès aux entraînements et devront être remis à leur
représentant légal.<br><br>

2. Cotisation annuelle<br>
Les adhérents doivent s’acquitter de la cotisation annuelle dont le montant est fixé chaque année
par le Bureau Directeur du club LYON PALME.<br>
Cette cotisation comprend notamment la licence FFESSM ainsi que l’assurance individuelle
obligatoire pour la pratique des activités du club.<br>
La cotisation annuelle se règle dès l’adhésion selon les modalités de paiement définies dans le
dossier d’adhésion (chèque(s)ou carte bancaire).<br>
En cas d’adhésion en cours d’année (uniquement à partir du mois de janvier), la cotisation sera
réduite au prorata des mois de pratique restants vis-à-vis de l’activité en piscine, autrement dit
jusqu’au mois de juin.<br>
De manière générale, les cotisations versées au club LYON PALME lui sont définitivement acquises.
Aucune cotisation ne sera remboursée en cours d’année en cas de départ, de démission, de
radiation du club ou de décès d’un adhérent.<br>
Les cas spécifiques (notamment pour cause de mutation professionnelle, de déménagement, de
changement de situation familiale, ou d’incapacité temporaire) seront étudiés par le Bureau
Directeur du club LYON PALME pour un éventuel remboursement partiel après déduction du
montant de la licence de l’assurance et d’une somme forfaitaire couvrant les frais de dossier.
Les adhérents bénéficiant d’une aide financière tierce partielle ou totale (comité d’entreprise, etc.)
peuvent demander un justificatif d’adhésion, auprès du Bureau Directeur du club LYON PALME, à
remettre à l’organisme concerné afin de faire valoir leur droit à remboursement.<br>
Le nonrèglement de la cotisation entraîne la perte de la qualité d’adhérent.<br><br>

3. Assemblée Générale<br>
L’ordre du jour, établi par le bureau Directeur, est adressé quinze jours à l’avance à l’ensemble des
adhérents. Tout adhérent peut proposer l’inscription d’un point à l’ordre du jour, au moins deux mois
avant la date de l’Assemblée Générale. Le Comité Directeur étudie la recevabilité de ce point et
donne réponse au requérant dans tous les cas.<br>
Lors de cette Assemblée Générale, les membres du bureau directeur ont pour mission de :<br>
● Présenter les différents rapports<br>
● Veiller à la bonne tenue des débats<br>
● Régler les incidents de séance<br>
● Contrôler les votes émis<br>
● Assurer la régularité des débats<br>
● Veiller à l’établissement d’un procès-verbal<br>
● Rédiger le procès-verbal.<br>
L’Assemblée Générale est appelée à se prononcer par vote à main levée sur le bilan financier et
moral de l’exercice écoulé et sur les propositions formulées par le Bureau Directeur.<br>
Elle vote le budget prévisionnel et débat sur les projets du Club.<br>
Le Bureau Directeur est investi des pouvoirs les plus étendus pour faire ou autoriser tous actes qui ne
sont pas réservés à l’Assemblée Générale, et qui ne sont contraires ni à la loi ni aux statuts :<br>
● Il élabore, modifie et décide de l’application du règlement intérieur du Club<br>
● Il veille au strict respect de l’amateurisme et à la stricte observation des règlements fédéraux.<br>
● Il contrôle la gestion des différentes activités sportives.<br>
● Il élabore, en concertation avec les encadrants des disciplines le calendrier des<br>
compétitions, des stages, des sorties extérieures et des formations techniquesd’encadrement.<br>
● Il constitue l’organe de juridiction disciplinaire dans le cadre du code de procédures fédérales et des sanctions annexé au règlement intérieur de la F.F.E.S.S.M.<br>
● Il entretient toutes les relations utiles avec les autres clubs de la fédération, les structures départementales, régionales et nationales, les médias, les structures commerciales liées à ses activités, ainsi qu’avec les pouvoirs publics.<br><br>

Le Bureau Directeur donne mandat au Président dans son rôle de Direction Générale de
l’association et l’investit des pouvoirs les plus étendus pour faire et autoriser tous les actes qui ne sont
pas réservés au Bureau Directeur.<br><br>

IV. Fonctionnement technique<br>
1. L'entraîneur principal Nages Avec Palmes (NAP)<br>
L'entraîneur principal est garant du respect de la réglementation en vigueur et référent technique
du club. Il coordonne l'activité de l'ensemble des encadrants, veille au maintien de leurs acquis
techniques et à ceux liés à la sécurité, sauvetage et secours à victime, et s'assure de l'adéquation
des méthodes pédagogiques. Toute décision concernant la sécurité est, en cas de désaccord, de
la seule compétence de l'entraîneur principal, qui applique et fait appliquer la réglementation en
vigueur.<br><br>

2. Les encadrants NAP<br>
L'enseignement et l'encadrement de l’activité NAP sont également assurés par des encadrants
désignés par l'entraîneur principal, ayant le brevet fédéral d’initiateur NAP. Les encadrants
s'engagent à respecter et à faire respecter les règles établies par la FFESSM, les réglementations en
vigueur et les consignes de sécurité données par l'entraîneur principal. Ils sont en charge du bon
déroulement du programme d'entraînement des séances en piscine.<br>
Ils peuvent prendre l’initiative d’organiser des sorties en milieu naturel, sous leur responsabilité et
dans le respect des règles établies par la FFESSM, le Bureau Directeur de LYON PALME et par
l'entraîneur principal.<br>
3. Les participants<br>
Tout participant à une séance doit impérativement être adhérent du club, c'est-à-dire avoir réglé sa
cotisation, remis un certificat médical, complété le formulaire d'inscription, et remis une autorisation
parentale pour les mineurs. Le certificat médical ne sera pas exigé pour la première séance d'essai
gratuite en piscine, ni pour un baptême en milieu naturel.<br>
4. Les entraînements en piscine<br>
Le club n’est pas responsable des vols ni des exactions commises contre des membres du club dans
l’enceinte de la piscine.<br>
Les adhérents se doivent de respecter les points suivants:<br>
● arriver 15 minutes avant l'heure de début des cours.<br>
● aider à l'installation et au rangement du matériel avant et après la séance .<br>
● se conformer au règlement intérieur et règles en vigueur de la piscine<br>
● ne jamais pratiquer d'activité sans être sous la responsabilité de l’encadrant responsable de
la séance d'entraînement.<br>
● respecter les consignes et le programme donnés par l'encadrant responsable de son
groupe.<br>
● ne pas quitter le bassin sans en avertir son encadrant (notamment pour les mineurs).<br>
Toute conduite irresponsable pourra se traduire par une exclusion du club sur décision du Bureau
Directeur.<br><br>

5. Les sorties en milieu naturel<br>
Respecter les consignes données par le ou les encadrants de la sortie.<br>
Les personnes non licenciées à la FFESSM sont interdites, sauf pour un baptême. Les personnes
licenciées mais non membres du club LYON PALME doivent être autorisées par le président ou
l'entraîneur principal.<br>
Les actes indélicats portant atteinte à la moralité et aux biens d'autrui sont sanctionnés par une
exclusion prononcée par le Bureau Directeur et peuvent, le cas échéant, faire l'objet d'un dépôt de
plainte.<br>
Toute conduite irresponsable pourra se traduire par une exclusion du club sur décision du Bureau
Directeur.<br><br>

V. Le matériel géré par le Club<br>
Le président, l'entraîneur principal et le responsable du matériel gèrent le matériel appartenant au
club, ils en autorisent l’usage ou l’emprunt aux membres du club. Le matériel ne sera prêté qu'à des
membres du club, c'est-à-dire aux personnes ayant acquitté leurs frais de cotisation club, exception
faite pour les séances d'essais. Dans tous les cas, l'emprunt de matériel du club ne sera autorisé que
si les personnes s'engagent à respecter la totalité des termes visant l'encadrement et la sécurité. Le
président peut décider de suspendre le prêt du matériel à une personne pour non-respect de
l’entretien courant. En cas de perte, vol ou détérioration du matériel prêté, tout ou partie des
chèques de caution seront encaissés uniquement sur décision du bureau.<br><br>

VI. Les Mineurs<br>
L’âge minimum est défini par le Bureau Directeur du club LYON PALME, c'est l'âge à la date
d'inscription qui est prise en compte. Au moment de l’inscription, ils doivent fournir une autorisation
parentale, leur permettant la pratique de la nage avec palme(s).<br><br>

VII. Radiation<br>
Conformément aux statuts du Club LYON PALME, la qualité de membre se perd en cours de saison
par ;<br>
● la démission notifiée par écrit,<br>
● la radiation prononcée par le Bureau Directeur ou l'entraîneur principal,<br>
● la radiation prononcée par la FFESSM.<br><br>

VIII. Modification du présent règlement intérieur<br>
Le règlement intérieur ne peut être modifié que par l'Assemblée Générale sur proposition du Bureau
Directeur ou du tiers des adhérents.<br>
Ce règlement entre en vigueur le jour de son adoption. Il annule et remplace le règlement intérieur
précédent.<br><br>

Bureau directeur de Lyon                                                                                           
